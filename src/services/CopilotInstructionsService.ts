import * as vscode from 'vscode';
import { ResearchNode } from '../models/types';
import { FileService } from './FileService';

const INSTRUCTIONS_PATH = '.github/copilot-instructions.md';

function nodeBlock(n: ResearchNode): string {
  const lines = [`### ${n.id} — ${n.title} \`[${n.type}]\``];
  if (n.source?.paper_id) {
    lines.push(`**Source:** ${n.source.paper_id}${n.source.location ? `, ${n.source.location}` : ''}`);
  }
  if (n.depends_on.length) {
    lines.push(`**Depends on:** ${n.depends_on.join(', ')}`);
  }
  if (n.tags.length) {
    lines.push(`**Tags:** ${n.tags.join(', ')}`);
  }
  if (n.body) {
    const snippet = n.body.length > 400 ? n.body.substring(0, 400) + '…' : n.body;
    lines.push('');
    lines.push(snippet);
  }
  return lines.join('\n');
}

export async function generateCopilotInstructions(
  nodes: ResearchNode[],
  fileService: FileService
): Promise<void> {
  const approved = nodes.filter((n) => n.status === 'approved');
  const draft = nodes.filter((n) => n.status === 'draft');

  const approvedByType = groupBy(approved, (n) => n.type);
  const draftByType = groupBy(draft, (n) => n.type);

  const approvedSection = Object.entries(approvedByType)
    .map(([type, ns]) => `#### ${capitalize(type)}s\n\n${ns.map(nodeBlock).join('\n\n')}`)
    .join('\n\n');

  const draftSection = draft.length
    ? Object.entries(draftByType)
        .map(([type, ns]) => `#### ${capitalize(type)}s\n\n${ns.map((n) => `- **${n.id}**: ${n.title}`).join('\n')}`)
        .join('\n\n')
    : '_None_';

  const content = `# Research Assistant — AI Context

> Auto-generated by the Research Assistant extension. Do not edit manually.

This workspace is managed by the **Research Assistant** VSCode extension.
Nodes in \`assets/\` and \`ideas/\` are Markdown files with YAML frontmatter describing mathematical research.

## Project Structure

| Path | Purpose |
|---|---|
| \`assets/\` | Theorem, lemma, proposition, definition, example, construction, remark nodes |
| \`ideas/\` | Research idea and strategy nodes |
| \`raw_papers/\` | Source PDF papers |
| \`manuscript/macro.tex\` | **All** \`\\newcommand\`, \`\\DeclareMathOperator\`, theorem environments |
| \`manuscript/notations.tex\` | **All** notation definitions — check before changing any symbol |
| \`manuscript/reference.bib\` | BibTeX bibliography |
| \`manuscript/main.tex\` | LaTeX document root |
| \`manuscript/sections/\` | One \`.tex\` file per paper section |
| \`papers.md\` | Paper index — one \`## slug\` section per paper |
| \`project.md\` | Project description, goals, open questions |

---

## Asset / Idea Node Frontmatter Schema

Each file in \`assets/\` or \`ideas/\` is a Markdown file with a YAML frontmatter block followed by a free-form Markdown body.

\`\`\`yaml
---
type: theorem | lemma | proposition | definition | example | construction | remark  # assets only
# type: idea  # ideas only — type is fixed and must not be changed
title: string
status: draft | approved | deprecated | archived
tags: [string, ...]
# Asset fields (type ≠ idea):
source:
  kind: paper | self_proved   # ONLY these two values are allowed
  paper_id: string            # required when kind = paper; matches a slug in papers.md
  location: string            # e.g. "Theorem 3.1"
# Array fields — the extension writes block format; flow format [id1, id2] is also valid YAML
depends_on:          # ids of nodes (assets or ideas) this result relies on
  - node_id
used_in:             # ids of nodes (assets or ideas) that use this result
  - node_id
# Idea field (type = idea):
related_assets:
  - node_id
---

Markdown body. Math syntax:

- **Inline math**: \`$x^2 + y^2 = r^2$\`
- **Block math** — \`$$\` must be on its own line, math on the next line(s), closing \`$$\` on its own line:

\`\`\`
$$
ax + by + cz = 0
$$
\`\`\`

Do NOT write \`$$ax+by=0$$\` on a single line — the renderer will not parse it as display math.
\`\`\`

**Rules:**
- The file name (without \`.md\`) is the node's \`id\`.
- **Ideas**: the \`type\` field must always remain \`idea\` — never change it.
- **Source kind**: only \`paper\` and \`self_proved\` are valid; do not use \`textbook\` or \`note\`.
- **depends_on / used_in / related_assets**: values must be valid node file names (without \`.md\`), i.e. the exact \`id\` of another node in \`assets/\` or \`ideas/\`.
- **Status after any edit**: whenever you create or modify a node or idea file, set \`status: draft\`. Do not promote a node to \`approved\` yourself — that is the researcher's decision.
- Only \`approved\` nodes should be cited in the manuscript.
- When writing or editing LaTeX, reference the source node in a comment: \`% [node_id]\`.

---

## papers.md Format

\`papers.md\` contains one section per registered paper. The slug is used as the \`paper_id\` in asset node frontmatter and as the BibTeX citation key.

\`\`\`markdown
## <slug>

- File: \`raw_papers/<slug>.pdf\`
- Description: <optional short description>
\`\`\`

Example:
\`\`\`markdown
## chebotarev_1923

- File: \`raw_papers/chebotarev_1923.pdf\`
- Description: Original proof of the Chebotarev density theorem.
\`\`\`

**Rules:**
- The slug must match the key used in \`manuscript/reference.bib\`.
- Do not rename a slug after it has been referenced in asset nodes.

---

## manuscript/reference.bib Format

Standard BibTeX. Each entry's key must match the slug in \`papers.md\`.

\`\`\`bibtex
@article{chebotarev_1923,
  author  = {Chebotarev, Nikolai},
  title   = {...},
  journal = {...},
  year    = {1923}
}
\`\`\`

---

## LaTeX Conventions

- **Do not introduce new \`\\newcommand\`** without first reading \`manuscript/macro.tex\`.
- **Do not change notation** without first reading \`manuscript/notations.tex\`.
- Use the theorem environments defined in \`macro.tex\` (e.g. \`\\begin{theorem}...\`).
- Split the manuscript into section-level files under \`manuscript/sections/\`.

---

## Approved Nodes (${approved.length})

${approvedSection || '_No approved nodes yet._'}

---

## Draft Nodes (${draft.length})

${draftSection}
`;

  try {
    await vscode.workspace.fs.createDirectory(fileService.resolve('.github'));
  } catch { /* already exists */ }
  await fileService.writeFile(INSTRUCTIONS_PATH, content);
}

function groupBy<T>(arr: T[], key: (item: T) => string): Record<string, T[]> {
  const result: Record<string, T[]> = {};
  for (const item of arr) {
    const k = key(item);
    (result[k] ??= []).push(item);
  }
  return result;
}

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
